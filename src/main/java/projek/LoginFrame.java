    private void doLogin() {
        String username = txtUser.getText().trim();
        String password = new String(txtPass.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            lblPesan.setForeground(new java.awt.Color(200, 0, 0));
            lblPesan.setText("Username dan password wajib diisi!");
            return;
        }

        lblPesan.setForeground(new java.awt.Color(0, 0, 200));
        lblPesan.setText("Memproses...");
        btnLogin.setEnabled(false);

        User user = userDAO.login(username, password);

        if (user == null) {
            lblPesan.setForeground(new java.awt.Color(200, 0, 0));
            lblPesan.setText("Username / password salah!");
            txtPass.setText("");
            btnLogin.setEnabled(true);
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                "Selamat datang, " + user.getUsername() + " (" + user.getRole() + ")",
                "Login Berhasil", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        dispose();
        AttendanceGUI gui = new AttendanceGUI(user);
        gui.setVisible(true);
    }

