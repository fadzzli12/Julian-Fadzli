    private void tab1SimpanAction() {
        String nama = tab1txtNama.getText().trim();
        String kelas = tab1txtKelas.getText().trim();
        if (nama.isEmpty() || kelas.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nama dan kelas harus diisi!", "Error", 0);
            return;
        }
        service.addStudent(nama, kelas);
        javax.swing.JOptionPane.showMessageDialog(this, "Siswa berhasil ditambahkan!", "Sukses", 1);
        tab1txtNama.setText("");
        tab1txtKelas.setText("");
    }

    private void tab2RefreshAction() {
        tab2model.setRowCount(0);
        for (Student s : service.getAllStudents()) {
            tab2model.addRow(new Object[] { s.getStudentId(), s.getName(), s.getClassName() });
        }
    }

    private void tab3RefreshAction() {
        tab3cbSiswa.removeAllItems();
        for (Student s : service.getAllStudents()) {
            tab3cbSiswa.addItem(s.getStudentId() + " - " + s.getName());
        }
    }

    private void tab3CatatAction() {
        int idx = tab3cbSiswa.getSelectedIndex();
        if (idx == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih siswa terlebih dahulu!", "Error", 0);
            return;
        }
        java.util.List<Student> students = service.getAllStudents();
        if (idx >= students.size()) return;
        Student s = students.get(idx);
        String status = (String) tab3cbStatus.getSelectedItem();
        service.recordAttendance(s.getStudentId(), status);
        javax.swing.JOptionPane.showMessageDialog(this,
                "Absensi \"" + s.getName() + "\" tercatat sebagai " + status, "Sukses", 1);
    }

    private void tab4RefreshAction() {
        tab4model.setRowCount(0);
        for (Attendance a : attendanceDAO.getAllAttendances()) {
            Student s = studentDAO.getStudentById(a.getStudentId());
            String siswa = s != null ? s.getName() : "Unknown";
            tab4model.addRow(new Object[] { a.getDate(), siswa, a.getTimeIn(), a.getStatus() });
        }
    }

    private void tab5RefreshAction() {
        tab5cbSiswa.removeAllItems();
        for (Student s : service.getAllStudents()) {
            tab5cbSiswa.addItem(s.getStudentId() + " - " + s.getName() + " (" + s.getClassName() + ")");
        }
    }

    private void tab5HapusAction() {
        int idx = tab5cbSiswa.getSelectedIndex();
        if (idx == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih siswa terlebih dahulu!", "Error", 0);
            return;
        }
        java.util.List<Student> students = service.getAllStudents();
        if (idx >= students.size()) return;
        Student s = students.get(idx);
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
                "Yakin hapus siswa \"" + s.getName() + "\" dan semua absensinya?", "Konfirmasi", 0);
        if (confirm == 0) {
            attendanceDAO.deleteByStudentId(s.getStudentId());
            studentDAO.deleteStudent(s.getStudentId());
            javax.swing.JOptionPane.showMessageDialog(this, "Siswa berhasil dihapus!", "Sukses", 1);
            tab5cbSiswa.removeItemAt(idx);
        }
    }

    public AttendanceGUI(User user) {
        this();
        currentUser = user;
        if (user != null) {
            setTitle("Sistem Absensi - " + user.getUsername() + " (" + user.getRole() + ")");
        }
        tab3cbStatus.removeAllItems();
        tab3cbStatus.addItem("HADIR");
        tab3cbStatus.addItem("IZIN");
        tab3cbStatus.addItem("SAKIT");
        tab3cbStatus.addItem("ALPA");
    }

